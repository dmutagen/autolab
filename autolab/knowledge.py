import json
from pathlib import Path
from typing import Dict, Any, List, Optional
from autolab.config import KB_FILE

class KnowledgeManager:
    def __init__(self):
        self.data: Dict[str, Any] = {}
        self.load()

    def load(self):
        if KB_FILE.exists():
            try:
                with open(KB_FILE, "r", encoding="utf-8") as f:
                    self.data = json.load(f)
            except Exception as e:
                print(f"Error loading knowledge base: {e}")
                self.data = {}
        else:
            self.data = {}

    def get_sample_conclusions(self, limit: int = 5) -> List[str]:
        return self.data.get("sample_conclusions", [])[:limit]

    def get_standard_equipment(self, subject: str = "") -> str:
        s_lower = subject.lower()
        if any(w in s_lower for w in ["дизайн", "design", "ui", "ux", "figma", "макет", "интерфейс", "прототип"]):
            return "Персональный компьютер IBM/AT, ОС Windows / Linux, графический редактор Figma / Pixso, веб-браузер, пакет векторной графики."
        elif any(w in s_lower for w in ["мобил", "android", "котлин", "kotlin"]):
            return "Персональный компьютер IBM/AT, ОС Windows / Linux, среда разработки Android Studio, эмулятор мобильного устройства."
        elif any(w in s_lower for w in ["субд", "баз", "данн", "sql", "sqlite", "mysql", "postgres"]):
            return "IBM-совместимый компьютер, MS Office, СУБД SQLite / MySQL Workbench / pgAdmin."
        elif any(w in s_lower for w in ["микро", "stm32", "avr", "proteus"]):
            return "IBM-совместимый компьютер, компилятор GCC / Keil, симулятор ISIS Proteus."
        elif any(w in s_lower for w in ["схем", "логик"]):
            return "IBM-совместимый компьютер, ПО для схемотехнического моделирования (Electronics Workbench / Multisim)."
        elif any(w in s_lower for w in ["безопасн", "иб", "защит", "крипт"]):
            return "IBM-совместимый компьютер, ОС Linux / Windows, специализированное ПО анализа защищенности, Python."
        elif any(w in s_lower for w in ["трпо", "тестир", "гит", "git"]):
            return "IBM-совместимый компьютер, среда разработки VS Code / IntelliJ IDEA, Git, средства отладки и тестирования."
        else:
            return "ПЭВМ IBM/AT, ОС Linux / Windows, среда программирования IntelliJ IDEA / VS Code, компилятор."

    def build_system_prompt(self, subject: str = "") -> str:
        equipment = self.get_standard_equipment(subject)
        sample_conclusions = "\n".join([f"- {c}" for c in self.get_sample_conclusions(4)])

